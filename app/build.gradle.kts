// Automatically ensure libv2ray.aar is present in app/libs even if the environment was restored
val libv2rayAar = file("libs/libv2ray.aar")
if (!libv2rayAar.exists() || libv2rayAar.length() == 0L) {
  libv2rayAar.parentFile.mkdirs()
  try {
    URI.create("https://github.com/2dust/AndroidLibXrayLite/releases/download/v26.10.21/libv2ray.aar")
      .toURL().openStream().use { input: java.io.InputStream ->
        libv2rayAar.outputStream().use { output: java.io.OutputStream ->
          input.copyTo(output)
        }
      }
  } catch (e: Throwable) {
    println("Could not auto-fetch libv2ray.aar: ${e.message}")
  }
}

